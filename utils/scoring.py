def calculate_disc(jawaban_p, jawaban_k):
    skor = {'D': 0, 'I': 0, 'S': 0, 'C': 0}
    for nomor, pilihan in jawaban_p.items():
        if nomor in DISC_MAPPING:
            tipe = DISC_MAPPING[nomor]['P'].get(pilihan, '*')
            if tipe in skor:
                skor[tipe] += 1
    for nomor, pilihan in jawaban_k.items():
        if nomor in DISC_MAPPING:
            tipe = DISC_MAPPING[nomor]['K'].get(pilihan, '*')
            if tipe in skor:
                skor[tipe] += 1
    return skor